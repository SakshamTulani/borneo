const phone = (
  ram: number,
  storage: number,
  colour: string,
  sku: string,
  mrp: number,
  price: number,
  stock?: Stock,
): SeedVariant => ({
  sku,
  options: { colour, storage: `${ram} GB + ${storage} GB` },
  mrp,
  price,
  ...(stock ? { stock } : {}),
});

const colour = (
  c: string,
  sku: string,
  mrp: number,
  price: number,
  stock?: Stock,
): SeedVariant => ({
  sku,
  options: { colour: c },
  mrp,
  price,
  ...(stock ? { stock } : {}),
});

const one = (sku: string, mrp: number, price: number, stock?: Stock): SeedVariant => ({
  sku,
  options: {},
  mrp,
  price,
  ...(stock ? { stock } : {}),
});

