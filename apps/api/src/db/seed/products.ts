import type { FamilyTier, ProductStatus } from '@borneo/shared';

/** Units on hand per warehouse, in `warehouses` order (blr, ggn, bhw). */
export type Stock = [number, number, number];

export type SeedVariant = {
  sku: string;
  options: Record<string, string>;
  /** Rupees; MRP is genuine (D-31). */
  mrp: number;
  price: number;
  stock?: Stock;
  /** Pre-order variants only: units that may be pre-sold (D-65). */
  preorderCap?: number;
};

export type SeedProduct = {
  slug: string;
  name: string;
  category: string;
  line: string;
  modelNumber: string;
  generation: number;
  tier: 'value' | 'upper_mid' | 'premium';
  familyTier: FamilyTier;
  status: ProductStatus;
  attributes: Record<string, unknown>;
  explainer?: string;
  whoFor?: string;
  notFor?: string;
  launchedAt?: string;
  /** Pre-orders: expected dispatch, days after seeding (D-64). */
  dispatchInDays?: [number, number];
  variants: SeedVariant[];
  faqs?: { question: string; answer: string }[];
};

